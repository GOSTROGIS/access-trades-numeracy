"""Bundle existing images and DejaVu fonts for PDF exports on both HTTP and file://."""
from __future__ import annotations

import argparse
import base64
import json
from pathlib import Path


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--font-directory', type=Path, default=Path('/usr/share/fonts/truetype/dejavu'))
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[2]
    quizzes = root / 'carpentry/intake-142/Quizzes'
    files = {
        'vendor/DejaVuSans.ttf': args.font_directory / 'DejaVuSans.ttf',
        'vendor/DejaVuSans-Bold.ttf': args.font_directory / 'DejaVuSans-Bold.ttf',
        '../../../brand/is4s-badge-512.png': root / 'brand/is4s-badge-512.png',
    }
    files.update({f'assets/{image.name}': image for image in sorted((quizzes / 'assets').glob('*.png'))})
    resources = {name: base64.b64encode(path.read_bytes()).decode('ascii') for name, path in files.items()}
    output = quizzes / 'vendor/pdf-resources.js'
    output.write_text('// Generated by source/quiz-generator/build-pdf-resources.py.\n'
                      'window.LectureQuizPDFResources=' + json.dumps(resources, separators=(',', ':')) + ';\n')
    print(f'Bundled {len(resources)} local resources: {output.relative_to(root)}')


if __name__ == '__main__':
    main()
