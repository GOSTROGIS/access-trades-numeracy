/* Real student journey: ordered cuts on one stock, sampled comparison, return and revision. */
'use strict';
const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs'), path = require('node:path');
const D = require('../../numeracy-hub/design/design-model.js');
const base = process.env.DESIGN_BASE_URL || 'http://127.0.0.1:8765';
const field = async (page, id, value) => { await page.fill(id, String(value)); await page.locator(id).blur(); };
const linkedProject = page => page.evaluate(() => AccessDesign.decode(document.getElementById('cnc-design-return').hash.slice(9)));
(async () => {
  const browser = await chromium.launch({ headless: true });
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true });
    await context.route(/^https?:\/\/(?!127\.0\.0\.1)/, route => route.abort());
    const page = await context.newPage(), errors = [];
    page.setDefaultTimeout(45000); page.setDefaultNavigationTimeout(60000);
    page.on('pageerror', e => errors.push(e.message));
    const p = D.create('plate'); p.title = 'Two-step pocket lesson'; p.brief = 'Rough a shallow pocket, finish its depth, and compare the corners.';
    p.geometry.params = { l: 30, w: 20 }; p.stock.width = 40; p.stock.height = 30;
    await page.goto(base + '/numeracy-hub/design/index.html#project=' + D.encode(p));
    await page.waitForFunction(() => window.DesignWorkshop);
    await page.click('[data-step="3"]');
    assert.equal(await page.inputValue('#comparison-mode'), 'pocket', 'Recommended operation and comparison goal agree');
    await field(page, '#comparison-depth', 2); await field(page, '#comparison-tolerance', .25);
    await page.click('[data-step="0"]'); await page.selectOption('#units', 'in'); await page.click('[data-step="3"]');
    assert.ok(Math.abs(Number(await page.inputValue('#comparison-depth')) * 25.4 - 2) < 1e-6, 'Goal display converts without scaling canonical dimensions');
    await field(page, '#comparison-tolerance', .02);
    assert.equal(await page.evaluate(() => DesignWorkshop.getProject().workflow.comparison.depthMm), 2, 'Editing another goal field in inches preserves exact unedited depth');
    await page.click('[data-step="0"]'); await page.selectOption('#units', 'mm'); await page.click('[data-step="3"]');
    await field(page, '#comparison-tolerance', .25);
    await field(page, '#comparison-depth', 11); assert.match(await page.locator('#notice').textContent(), /stock depth/);
    assert.equal(await page.inputValue('#comparison-depth'), '2', 'Invalid goal is rejected and previous value restored');
    await page.click('#open-cnc');
    await page.waitForFunction(() => window.CNCBuilder && CNCBuilder.getState() && window.AccessDesignComparison);
    const manual = await page.evaluate(() => CNCBuilder.getState());
    await page.locator('#cnc-operation').evaluate(el => { el.open = true; });
    await field(page, '#cnc-op-label', 'Rough pocket'); await field(page, '#cnc-op-depth', 1); await field(page, '#cnc-op-tool', 3);
    await page.click('#cnc-op-generate');
    assert.match(await page.locator('#cnc-op-status').textContent(), /Program checked/);
    await page.click('#cnc-op-capture');
    let linked = await linkedProject(page);
    assert.equal(linked.workflow.results[0].kind, 'check'); assert.equal(linked.workflow.results[0].comparison, undefined, 'Preflight alone cannot claim measured material');
    await page.click('#cnc-op-simulate');
    assert.match(await page.locator('#cnc-op-status').textContent(), /preview completed/);
    await page.click('#cnc-op-compare');
    await page.click('#cnc-op-capture'); linked = await linkedProject(page);
    const rough = linked.workflow.results.at(-1);
    assert.equal(rough.kind, 'simulation'); assert.ok(rough.comparison, 'Completed preview includes comparison evidence');
    assert.equal(rough.comparison.status, 'needs-work'); assert.ok(rough.comparison.metrics.excessVolumeMm3 > 500, 'Shallow roughing still leaves material inside the intended pocket');
    await page.click('#cnc-op-generate');
    assert.equal(await page.locator('#cnc-op-compare').isDisabled(), true, 'Regeneration clears comparison even if the plan is unchanged');
    await page.click('#cnc-op-capture');
    const regenerated = (await linkedProject(page)).workflow.results.at(-1);
    assert.equal(regenerated.kind, 'check'); assert.equal(regenerated.comparison, undefined, 'A regenerated preflight cannot inherit the previous simulation map');
    await page.click('#cnc-step-duplicate');
    await field(page, '#cnc-op-label', 'Finish pocket'); await field(page, '#cnc-op-depth', 2);
    await page.click('#cnc-step-up');
    assert.equal((await linkedProject(page)).workflow.sequence.steps[0].label, 'Finish pocket');
    await page.click('#cnc-step-down');
    assert.deepEqual((await linkedProject(page)).workflow.sequence.steps.map(s => s.label), ['Rough pocket', 'Finish pocket']);
    assert.equal(await page.locator('#cnc-op-capture').isDisabled(), true, 'Order/depth changes invalidate captures');
    await page.click('#cnc-op-generate');
    assert.match(await page.locator('#cnc-op-status').textContent(), /2 ordered steps/);
    const code = await page.locator('#cnc-op-code').textContent();
    assert.equal((code.match(/^O\d+/gm) || []).length, 1); assert.equal((code.match(/^M30$/gm) || []).length, 1);
    assert.ok(code.indexOf('STEP 1: Rough pocket') < code.indexOf('STEP 2: Finish pocket'));
    assert.match(code, /T1\s*M0?6/); assert.match(code, /T2\s*M0?6/);
    await page.click('#cnc-op-simulate'); await page.click('#cnc-op-compare'); await page.click('#cnc-op-capture'); linked = await linkedProject(page);
    const finished = linked.workflow.results.at(-1);
    assert.equal(finished.operationCount, 2); assert.equal(finished.operationKind, 'sequence');
    assert.ok(finished.comparison.metrics.excessVolumeMm3 < rough.comparison.metrics.excessVolumeMm3 / 4, 'Finishing reduces material left by roughing on the same stock');
    assert.ok(finished.removedVolumeMm3 > rough.removedVolumeMm3 * 1.8, 'Cumulative removal includes both steps');
    assert.ok(finished.comparison.overlay.cells.length <= 2304); assert.equal(finished.materialSnapshot, undefined, 'Full sample arrays are not embedded in the project');
    assert.deepEqual(await page.evaluate(() => CNCBuilder.getState()), manual, 'Sequence simulation preserves the manual draft');
    await page.setViewportSize({ width: 390, height: 844 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, 'CNC sequencing fits a phone');
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.reload(); await page.waitForFunction(() => window.CNCBuilder && CNCBuilder.getState());
    await page.locator('#cnc-design-target').evaluate(el => { el.open = true; });
    assert.deepEqual((await linkedProject(page)).workflow.sequence.steps.map(s => s.label), ['Rough pocket', 'Finish pocket']);
    assert.deepEqual((await linkedProject(page)).workflow.results.at(-1).comparison, finished.comparison, 'Comparison persists across reload');
    await page.click('#cnc-design-return'); await page.waitForFunction(() => window.DesignWorkshop);
    await page.click('#new-dialog [value="start"]');
    await page.click('[data-step="3"]');
    assert.equal(await page.locator('#operation-sequence li').count(), 2);
    assert.equal(await page.locator('#machine-results .comparison-figure svg').count(), 2);
    assert.match(await page.locator('#machine-results').textContent(), /Current design.*simulation/s);
    if (process.env.DESIGN_SCREENSHOT_DIR) { fs.mkdirSync(process.env.DESIGN_SCREENSHOT_DIR, { recursive: true }); await page.screenshot({ path: path.join(process.env.DESIGN_SCREENSHOT_DIR, 'sequence-comparison-desktop.png'), fullPage: true }); }
    await field(page, '#comparison-depth', 3);
    assert.ok(await page.evaluate(() => DesignWorkshop.getProject().workflow.results.every(r => AccessDesignWorkflow.resultStatus(DesignWorkshop.getProject(), r).stale)), 'Changing the target invalidates earlier comparison evidence');
    await page.click('#undo');
    assert.equal(await page.evaluate(() => { const p = DesignWorkshop.getProject(); return AccessDesignWorkflow.resultStatus(p, p.workflow.results.at(-1)).stale; }), false);
    await page.click('[data-step="4"]');
    const downloading = page.waitForEvent('download'); await page.click('#submission-download');
    const submission = JSON.parse(fs.readFileSync(await (await downloading).path(), 'utf8'));
    assert.deepEqual(submission.project.workflow.results.at(-1).comparison, finished.comparison); assert.equal(submission.project.workflow.sequence.steps.length, 2);
    await page.evaluate(() => { window.print = () => {}; }); await page.click('#print-sheet');
    assert.match(await page.locator('#print-summary').textContent(), /Machining sequence/); assert.ok(await page.locator('#print-summary .comparison-figure svg').count() > 0);
    await page.setViewportSize({ width: 320, height: 840 }); await page.click('[data-step="3"]');
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, 'Workshop goals and comparison fit 320px');
    if (process.env.DESIGN_SCREENSHOT_DIR) await page.screenshot({ path: path.join(process.env.DESIGN_SCREENSHOT_DIR, 'sequence-comparison-mobile.png'), fullPage: true });
    assert.deepEqual(errors, []);
    console.log('PASS: ordered rough/finish steps on one stock, reorder and invalidation, actual sampled comparison improvement, bounded capture, reload, return, units/invalid goal, undo, submission, worksheet and phone layout');
    await context.close();
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
